import { expect, test, type Page } from '@playwright/test'
import { adminApi, isoDate, mobile10, outletWithStock } from '../helpers'

async function signIn(page: Page, o: { mobileNumber: string; generatedPassword: string }) {
  // window.print() would block a headless run; window.confirm is accepted automatically.
  await page.addInitScript(() => { window.print = () => undefined })
  page.on('dialog', (d) => void d.accept())
  await page.goto('/login')
  await page.getByLabel('Mobile number or username').fill(o.mobileNumber)
  await page.getByLabel('Password', { exact: true }).fill(o.generatedPassword)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page).toHaveURL(/\/outlet$/)
}

test('create a bill through the UI: search, add, qty limit, discount, save', async ({ page }) => {
  const ctx = await outletWithStock(await adminApi(), { price: 100, stock: 3, allocated: 3 })
  await signIn(page, ctx.outlet)
  await page.goto('/outlet/billing')
  await page.getByRole('button', { name: 'Create new bill' }).first().click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Customer mobile').fill(mobile10())
  await dialog.getByLabel('Customer name').fill('UI Customer')
  await dialog.getByLabel('Add product').fill(ctx.item.name)
  await dialog.getByRole('button', { name: 'Search' }).click()
  await expect(dialog.getByText('In stock: 3')).toBeVisible()
  await dialog.getByRole('button', { name: 'Add', exact: true }).click()
  const qty = dialog.getByRole('textbox').filter({ hasText: '' }).locator('input[inputmode="numeric"]').first()
  await qty.fill('9')
  await qty.blur()
  await expect(dialog.getByText('max 3')).toBeVisible()
  await expect(dialog.getByText('₹300.00').first()).toBeVisible()
  await dialog.getByRole('button', { name: 'Complete bill' }).click()
  await expect(page.getByText('Bill completed')).toBeVisible()
  await page.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('tab', { name: 'Recent bills' }).click()
  await expect(page.getByText('UI Customer')).toBeVisible()
})

