package com.sanasboutique.backend.catalog.entity;


import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

import java.math.BigDecimal;
import java.time.Instant;

/**
 * The actual sellable/rentable thing, belonging directly to a Service - one
 * common shape for every business line. quantity is optional: filled in
 * for a stock-tracked item (a jewelry piece, a bolt of fabric), left null
 * for a pure labor service (a facial, a stitching job) that has no stock
 * to count. price is read against the parent Service's priceUnit to know
 * what it means (flat, per day, per meter, ...).
 *
 * itemCode is generated by CatalogController right after the first save
 * (it's derived from this entity's own id, so it can't be known before
 * that insert happens) and is never user-entered. It doubles as both the
 * printed barcode's content and the search key - see itemCode's own doc.
 */
@Entity
@Table(name = "service_item")
public class ServiceItem {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "service_id", nullable = false)
    private CatalogService service;

    @Column(nullable = false, length = 150)
    private String name;

    @Column(length = 255)
    private String description;

    /**
     * Generated, not user-entered (see class doc). Nullable at the DB level
     * only for the brief instant between this row's insert and the
     * follow-up update that sets it - by the time any request can read
     * this item back, it's always set.
     */
    @Column(name = "item_code", length = 50, unique = true)
    private String itemCode;

    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal price;

    /** Null means "not stock-tracked" (e.g. a facial). Non-null is the count on hand at HQ. */
    @Column private Integer quantity;

    /** The outlet that owns this product (and its price and stock). */
    @Column(name = "outlet_id")
    private Long outletId;

    /** Optional value of one piece if it is lost (jewellery); pre-fills the missing charge at a rental return. */
    @Column(name = "replacement_value", precision = 10, scale = 2)
    private BigDecimal replacementValue;

    @Column(name = "is_active", nullable = false)
    private boolean active = true;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected ServiceItem() {
        // JPA
    }

    public ServiceItem(
            CatalogService service,
            String name,
            String description,
            BigDecimal price,
            Integer quantity) {
        this.service = service;
        this.name = name;
        this.description = description;
        this.price = price;
        this.quantity = quantity;
    }

    public Long getId() {
        return id;
    }

    public CatalogService getService() {
        return service;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getItemCode() {
        return itemCode;
    }

    public void setItemCode(String itemCode) {
        this.itemCode = itemCode;
    }

    public BigDecimal getPrice() {
        return price;
    }

    public void setPrice(BigDecimal price) {
        this.price = price;
    }

    public Long getOutletId() {
        return outletId;
    }

    public BigDecimal getReplacementValue() {
        return replacementValue;
    }

    public void setReplacementValue(BigDecimal replacementValue) {
        this.replacementValue = replacementValue;
    }

    public void setOutletId(Long outletId) {
        this.outletId = outletId;
    }

    public Integer getQuantity() {
        return quantity;
    }

    public void setQuantity(Integer quantity) {
        this.quantity = quantity;
    }

    public boolean isActive() {
        return active;
    }

    public void setActive(boolean active) {
        this.active = active;
    }
}
