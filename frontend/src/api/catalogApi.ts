import { apiClient } from './client'

// ---------- Price units ----------

export interface PriceUnit {
  id: number
  name: string
}

export interface PriceUnitPayload {
  name: string
}

export const priceUnitApi = {
  list: () => apiClient.get<PriceUnit[]>('/price-units').then((r) => r.data),
  create: (payload: PriceUnitPayload) => apiClient.post<PriceUnit>('/price-units', payload).then((r) => r.data),
}

// ---------- Services ----------

export interface Service {
  id: number
  name: string
  description: string | null
  priceUnitId: number
  priceUnitName: string
  active: boolean
  itemCount: number
  bookingMode: string | null
  prebookEnabled: boolean
  /** The outlet module this service opens: a built-in one, or CUSTOM = a franchisor-created billing module. */
  module: 'RENTAL' | 'PARLOUR' | 'STITCHING' | 'SALES' | 'CUSTOM'
  billingModuleId: number | null
  billingModuleName: string | null
}

export interface ServicePayload {
  name: string
  description?: string | null
  priceUnitId: number
  module: string
  /** With module CUSTOM: which billing module. */
  billingModuleId?: number | null
}

/** A franchisor-created simple billing module (docs/features/custom-billing-modules.md). code: in bill numbers, generated from the name. */
export interface BillingModule { id: number; name: string; code: string; icon: string; active: boolean; serviceCount: number }
export const billingModuleApi = {
  list: () => apiClient.get<BillingModule[]>('/billing-modules').then((r) => r.data),
  previewCode: (name: string) => apiClient.get<{ code: string }>('/billing-modules/code-preview', { params: { name } }).then((r) => r.data.code),
  create: (payload: { name: string; icon: string }) => apiClient.post<BillingModule>('/billing-modules', payload).then((r) => r.data),
  update: (id: number, payload: { name: string; icon: string }) => apiClient.put<BillingModule>(`/billing-modules/${id}`, payload).then((r) => r.data),
  setActive: (id: number, active: boolean) => apiClient.patch<BillingModule>(`/billing-modules/${id}/active`, { active }).then((r) => r.data),
}

export const serviceApi = {
  list: () => apiClient.get<Service[]>('/services').then((r) => r.data),
  create: (payload: ServicePayload) => apiClient.post<Service>('/services', payload).then((r) => r.data),
  update: (id: number, payload: ServicePayload) =>
    apiClient.patch<Service>(`/services/${id}`, payload).then((r) => r.data),
  setActive: (id: number, active: boolean) =>
    apiClient.patch<Service>(`/services/${id}/active`, { active }).then((r) => r.data),
}

// ---------- Service items ----------
//
// Items belong directly to a Service (no category level). itemCode is
// generated by the backend on creation — never sent by the client.

export interface ServiceItemImage {
  id: number
  imageUrl: string
}

export interface ServiceItem {
  id: number
  serviceId: number
  serviceName: string
  priceUnitName: string
  name: string
  description: string | null
  itemCode: string | null
  price: number
  quantity: number | null
  active: boolean
  images: ServiceItemImage[]
}

export interface ServiceItemPayload {
  name: string
  description?: string | null
  price: number
  quantity?: number | null
}

// Products belong to outlets and are managed by the outlet itself; the admin
// can only look a product up by its code.
export const serviceItemApi = {
  findByItemCode: (itemCode: string) =>
    apiClient.get<ServiceItem>(`/service-items/by-code/${encodeURIComponent(itemCode)}`).then((r) => r.data),
}

export function extractErrorMessage(error: unknown): string {
  if (
    typeof error === 'object' &&
    error !== null &&
    'response' in error &&
    typeof (error as { response?: { data?: { message?: string } } }).response?.data?.message === 'string'
  ) {
    return (error as { response: { data: { message: string } } }).response.data.message
  }
  return 'Something went wrong. Please try again.'
}
